#!/usr/bin/env bash
# Resolves this repo's cross-repo dependency on thenewurbankid-web/construct's
# core/CLI (#540 step 2): fetches packages/{core,ast,engine,cli} at a pinned
# construct ref into ./packages/{core,ast,engine,cli}, git-ignored here, never
# committed to this repo.
#
# Why fetch-at-build-time instead of vendoring (committing) a copy:
#   - Nothing from construct is published to any npm registry yet
#     (packages/cli, packages/core declare `publishConfig` pointing at GitHub
#     Packages, but that has only ever been a dry run -- see construct's own
#     project history). `npm install github:thenewurbankid-web/construct#<ref>`
#     is not viable either: construct's root package.json is workspace-shaped
#     for its own monorepo, not an installable package exposing packages/core
#     by path, and ui/server's imports expect the physical file layout
#     `<repo-root>/packages/{core,ast,engine,cli}/*.mjs`, not a package
#     resolved by name.
#   - construct's own repo already vendors (COPIES, commits) these same four
#     directories for its own npm-distribution story (see construct's
#     `ui/pack-npm.sh` + `ui/cockpit-npm-meta/`, #485) -- copying the
#     directories at the same relative depth is a proven pattern there. This
#     script does the same copy, but does NOT commit the result, for one
#     reason specific to this repo split (#540):
#   - **`thenewurbankid-web/cockpit` is currently a PUBLIC repo, while
#     `thenewurbankid-web/construct` is currently PRIVATE.** Committing a copy
#     of construct's core source into this repo's git history would make
#     previously-private code public ahead of construct's own, separately
#     decided and sequenced visibility flip (construct#540 step 7 is
#     explicit that this is an owner decision, not automatic). Fetching the
#     four directories at build/install time instead means this repo's git
#     history and pushed refs never contain that source -- only this script,
#     which needs read access to construct (via the builder's own `gh`
#     login or SSH key) for as long as construct stays private. Once
#     construct goes public (or #480 publishes @line/construct-core for
#     real), the auth requirement drops away and this script's `git clone`
#     keeps working unchanged; a real `npm install`-based dependency can
#     replace it entirely at that point.
#
# Why these four directories specifically: ui/server/src/index.mjs (and
# several sibling modules) import '../../../packages/core/*.mjs' and
# '../../../packages/engine/*.mjs' by relative path -- 3 levels up from
# ui/server/src puts you at this repo's root, so packages/core and
# packages/engine must exist there. packages/core imports packages/ast the
# same way, and packages/engine/botRunner.mjs resolves
# '../cli/construct.mjs' relative to itself at runtime, so packages/ast and
# packages/cli come along even though ui/server never imports them directly.
# Keeping `ui/client`/`ui/server` at those exact names (not flattened to
# `client`/`server`) is what keeps all of this working with ZERO source
# changes to the copied code.
#
# Usage:
#   scripts/vendor-construct.sh                  # uses the pinned default below
#   CONSTRUCT_REF=<tag-or-sha> scripts/vendor-construct.sh
#
# Requires: git, and (while construct is private) read access to
# thenewurbankid-web/construct -- either `gh auth login` (its git credential
# helper is picked up automatically) or an SSH key with access
# (CONSTRUCT_REPO=git@github.com:thenewurbankid-web/construct.git).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

CONSTRUCT_REPO="${CONSTRUCT_REPO:-https://github.com/thenewurbankid-web/construct.git}"
# Pinned at the commit this copy was originally split from (construct's
# work/2026-09-23 branch, #540 steps 1-2). Bump deliberately, not casually --
# each bump should be its own reviewed commit here.
CONSTRUCT_REF="${CONSTRUCT_REF:-434962fcfe9ece14afe6c0c7a44312bfd5bcaa7f}"

WORKDIR="$(mktemp -d)"
trap 'rm -rf "$WORKDIR"' EXIT

echo "== Fetching packages/{core,ast,engine,cli} @ ${CONSTRUCT_REPO}#${CONSTRUCT_REF} =="
git init -q "$WORKDIR"
git -C "$WORKDIR" remote add origin "$CONSTRUCT_REPO"
git -C "$WORKDIR" fetch --depth 1 origin "$CONSTRUCT_REF"
git -C "$WORKDIR" sparse-checkout init --cone
git -C "$WORKDIR" sparse-checkout set packages/core packages/ast packages/engine packages/cli
git -C "$WORKDIR" checkout -q FETCH_HEAD

RESOLVED_SHA="$(git -C "$WORKDIR" rev-parse FETCH_HEAD)"
for pkg in core ast engine cli; do
  [ -d "$WORKDIR/packages/$pkg" ] || { echo "Missing packages/$pkg at $RESOLVED_SHA -- aborting." >&2; exit 1; }
done

rm -rf packages/core packages/ast packages/engine packages/cli
mkdir -p packages
for pkg in core ast engine cli; do
  cp -r "$WORKDIR/packages/$pkg" "packages/$pkg"
done

cat > packages/.vendored-from <<EOF
# Generated by scripts/vendor-construct.sh -- do not hand-edit.
# packages/{core,ast,engine,cli} in this tree are a fetched (not committed)
# copy of thenewurbankid-web/construct at the commit below.
repo=${CONSTRUCT_REPO}
ref=${CONSTRUCT_REF}
resolved_sha=${RESOLVED_SHA}
fetched_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF

echo "== Vendored ${RESOLVED_SHA} into ./packages/{core,ast,engine,cli} (git-ignored, not committed) =="
